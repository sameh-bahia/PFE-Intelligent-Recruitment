package com.AppRecrutement.AppRecrutement.model;

/**
 * Enum représentant le niveau d'étude
 */
public enum NiveauEtude {
    BAC,              // Baccalauréat
    DUT_BTS,          // DUT ou BTS
    LICENCE,          // Licence (3 ans après bac)
    MASTER,           // Master (5 ans après bac)
    INGENIEUR,        // Diplôme d'ingénieur
    DOCTORAT,         // Doctorat
    SANS_EXIGENCE     // Aucune exigence de niveau
}
